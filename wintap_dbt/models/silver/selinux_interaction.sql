select
    md5(concat_ws('||',
        'selinux_interaction',
        coalesce(cast(PID as varchar), '<null>'),
        coalesce(PidHash, '<null>'),
        coalesce(ProcessName, '<null>'),
        coalesce(AgentId, '<null>'),
        coalesce(Hostname, '<null>'),
        coalesce(cast(EventTime as varchar), '<null>'),
        coalesce(cast(FirstSeen as varchar), '<null>'),
        coalesce(cast(LastSeen as varchar), '<null>'),
        coalesce(cast(PolicyEpoch as varchar), '<null>'),
        coalesce(cast(SSid as varchar), '<null>'),
        coalesce(cast(TSid as varchar), '<null>'),
        coalesce(SContext, '<null>'),
        coalesce(TContext, '<null>'),
        coalesce(TClass, '<null>'),
        coalesce(Permission, '<null>'),
        coalesce(cast(RequestedMask as varchar), '<null>'),
        coalesce(cast(Novel as varchar), '<null>')
    )) as event_id,
    'selinux_interaction' as event_family,
    MessageType as message_type,
    PID as pid,
    PidHash as pid_hash,
    ProcessName as process_name,
    AgentId as agent_id,
    Hostname as hostname,
    EventTime as raw_event_time,
    FirstSeen as raw_first_seen,
    LastSeen as raw_last_seen,
    {{ unix_or_timestamp_expr('EventTime') }} as event_time,
    {{ win32_to_timestamp_expr('FirstSeen') }} as first_seen,
    {{ win32_to_timestamp_expr('LastSeen') }} as last_seen,
    EventCount as event_count,
    num_dups as num_raw_rows,
    PolicyEpoch as policy_epoch,
    SSid as s_sid,
    TSid as t_sid,
    SContext as s_context,
    TContext as t_context,
    TClass as t_class,
    Permission as permission,
    RequestedMask as requested_mask,
    Novel as novel,
    dayPK as day_pk,
    hourPK as hour_pk
from {{ ref('stg_raw_selinuxinteraction') }}
