select
    'windows' os_family,
    agentid agent_id,
    hostname,
    pidhash pid_hash,
    any_value(pid) os_pid,
    processname process_name,
    connid conn_id,
    protocol protocol,
    {{ win32_to_minute_timestamp_expr('cast(firstseenms as bigint)') }} incr_start,
    sourceipaddressstring source_ip_address_string,
    destinationipaddressstring destination_ip_address_string,
    {{ int_to_ip_expr('cast(localipaddr as bigint)') }} local_ip_addr,
    localipaddr local_ip_int,
    localipprivategateway local_ip_private_gateway,
    localport local_port,
    {{ int_to_ip_expr('cast(remoteipaddr as bigint)') }} remote_ip_addr,
    remoteipaddr remote_ip_int,
    remoteipprivategateway remote_ip_private_gateway,
    remoteport remote_port,
    sum(eventcount) total_events,
    sum(packetsize) total_size,
    count(*) num_raw_rows,
    sum(case when network_activity = 'tcpipaccept' then eventcount end) tcp_accept_count,
    sum(case when network_activity = 'tcpipconnect' then eventcount end) tcp_connect_count,
    sum(case when network_activity = 'tcpipdisconnect' then eventcount end) tcp_disconnect_count,
    sum(case when network_activity = 'tcpipreconnect' then eventcount end) tcp_reconnect_count,
    sum(case when network_activity in ('tcpiprecv', 'tcpiprecvipv6') then eventcount end) tcp_recv_count,
    sum(case when network_activity in ('tcpiprecv', 'tcpiprecvipv6') then packetsize end) tcp_recv_size,
    sum(case when network_activity = 'tcpipretransmit' then eventcount end) tcp_retransmit_count,
    sum(case when network_activity in ('tcpipsend', 'tcpipsendipv6') then eventcount end) tcp_send_count,
    sum(case when network_activity in ('tcpipsend', 'tcpipsendipv6') then packetsize end) tcp_send_size,
    sum(case when network_activity = 'tcpiptcpcopy' then eventcount end) tcp_tcpcopy_count,
    sum(case when network_activity = 'tcpiptcpcopy' then packetsize end) tcp_tcpcopy_size,
    sum(case when network_activity = 'udpiprecv' then eventcount end) udp_recv_count,
    sum(case when network_activity = 'udpiprecv' then packetsize end) udp_recv_size,
    sum(case when network_activity = 'udpipsend' then eventcount end) udp_send_count,
    sum(case when network_activity = 'udpipsend' then packetsize end) udp_send_size,
    min(eventcount) min_10sec_eventcount,
    max(eventcount) max_10sec_eventcount,
    min(minpacketsize) min_size,
    max(maxpacketsize) max_size,
    sum(packetsizesquared) sq_size,
    max(case when network_activity in ('tcpiprecv', 'tcpiprecvipv6') then eventcount end) max_tcp_recv_count,
    min(case when network_activity in ('tcpiprecv', 'tcpiprecvipv6') then minpacketsize end) min_tcp_recv_size,
    max(case when network_activity in ('tcpiprecv', 'tcpiprecvipv6') then maxpacketsize end) max_tcp_recv_size,
    sum(case when network_activity in ('tcpiprecv', 'tcpiprecvipv6') then packetsizesquared end) sq_tcp_recv_size,
    max(case when network_activity in ('tcpipsend', 'tcpipsendipv6') then eventcount end) max_tcp_send_count,
    min(case when network_activity in ('tcpipsend', 'tcpipsendipv6') then minpacketsize end) min_tcp_send_size,
    max(case when network_activity in ('tcpipsend', 'tcpipsendipv6') then maxpacketsize end) max_tcp_send_size,
    sum(case when network_activity in ('tcpipsend', 'tcpipsendipv6') then packetsizesquared end) sq_tcp_send_size,
    max(case when network_activity = 'udpiprecv' then eventcount end) max_udp_recv_count,
    min(case when network_activity = 'udpiprecv' then minpacketsize end) min_udp_recv_size,
    max(case when network_activity = 'udpiprecv' then maxpacketsize end) max_udp_recv_size,
    sum(case when network_activity = 'udpiprecv' then packetsizesquared end) sq_udp_recv_size,
    max(case when network_activity = 'udpipsend' then eventcount end) max_udp_send_count,
    min(case when network_activity = 'udpipsend' then minpacketsize end) min_udp_send_size,
    max(case when network_activity = 'udpipsend' then maxpacketsize end) max_udp_send_size,
    sum(case when network_activity = 'udpipsend' then packetsizesquared end) sq_udp_send_size,
    {{ win32_to_timestamp_expr('min(cast(firstseenms as bigint))') }} first_seen,
    {{ win32_to_timestamp_expr('max(cast(lastseenms as bigint))') }} last_seen
from (
    -- Compare one canonical spelling, without changing the bronze/raw event.
    select *, lower(replace(ipevent, '/', '')) as network_activity
    from {{ ref('stg_raw_process_conn_incr') }}
)
group by all
